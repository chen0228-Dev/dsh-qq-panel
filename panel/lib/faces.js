/** 去掉 summary 自带的方括号（`[汪星人]` → `汪星人`），免得拼出 `[[汪星人]]`。 */
function stripBrackets(text) {
  return String(text || '').trim().replace(/^[\[【]/, '').replace(/[\]】]$/, '')
}

/** 图片段 summary 里带「表情」字样（如 `[动画表情]`）的，就是表情包而不是普通图。 */
const IMAGE_FACE_SUMMARY = /\[.+表情\]/

/**
 * 判断一个段是不是「表情类」。后续判空逻辑要用它：
 * 一条消息如果只剩表情段，去掉之后就成了空串，得当成「有内容」而不是「没说话」。
 */
export function isFaceLikeSeg(seg) {
  if (!seg || typeof seg !== 'object') return false
  const type = seg.type
  if (type === 'face' || type === 'mface' || type === 'marketface') return true
  if (type === 'image') {
    const data = seg.data || {}
    return String(data.sub_type) === '1' || IMAGE_FACE_SUMMARY.test(String(data.summary || ''))
  }
  return false
}

/**
 * 把一个段翻成给模型看的文字。
 * 返回 null 表示「不是我负责的段」，调用方自己去处理（文字、图片、at 之类）。
 */
export function describeFaceSeg(seg) {
  if (!seg || typeof seg !== 'object') return null
  const data = seg.data || {}

  if (seg.type === 'face') {
    const id = String(data.id ?? '')
    const name = faceName(id)
    // 查不到名字就退回编号：模型至少知道「他发了个表情」，比凭空丢掉强
    return `[表情:${name || id}]`
  }

  if (seg.type === 'mface' || seg.type === 'marketface') {
    // 超级表情/商城表情：summary 最好用（`[汪星人]` 这种，本身就带方括号）
    const summary = stripBrackets(data.summary)
    if (summary) return `[超级表情:${summary}]`
    // 只有 id/key、没有名字时，只能笼统说一句「他发了个超级表情」
    if (data.emoji_id || data.key) return '[超级表情]'
    return '[超级表情]'
  }

  if (seg.type === 'image') {
    const summary = stripBrackets(data.summary)
    if (String(data.sub_type) === '1' || IMAGE_FACE_SUMMARY.test(String(data.summary || ''))) {
      return summary ? `[表情包:${summary}]` : '[表情包]'
    }
    return null
  }

  return null
}
