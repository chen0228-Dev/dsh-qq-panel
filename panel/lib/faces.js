/**
 * 取中文名。查不到返回空串而不是 undefined ——
 * 调用方几乎都是直接往模板串里拼，`undefined` 会真的被拼进提示词里给模型看。
 */
export function faceName(id) {
  return FACE_NAMES[id] || ''
}

/**
 * 常用表情。不筛关键词时只报这一批，275 个全倒出来太占上下文。
 * 顺序是官方表情面板里最顺手的那些，不是按编号排的。
 *
 * 注意 40 不在这张表里（原表 39 之后直接跳到 41），拿到时会退回成 `[表情:40]`。
 * 保留是因为这份顺序是跟着官方面板抄的，删一个反而容易让人以为表抄漏了。
 */
