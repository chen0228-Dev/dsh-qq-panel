/**
 * 认「对方这句是不是在让她做事」。
 *
 * 【为什么需要】
 * 她的人格写得很重（有自己的生活、自己的看法、不是助理），好处是像人，
 * 副作用是**对方明确让她干点什么，她经常只回一句话就过去了**。
 * 用户的原话：「即使我在对话中让他去干某件事他也没去做」。
 *
 * 真人也这样 —— 朋友让你顺手带杯咖啡，你嘴上可能嘟囔两句，但你会带。
 * 不会只回一句「好啊」然后坐着不动。所以这不是要求她变成工具人，
 * 是要她**把答应的事真办了**。
 *
 * 【为什么用正则而不是让模型自己判断】
 * 模型已经在处理人格、状态、上下文，再让它自己"识别这是不是指令"很容易漏。
 * 这里只做一件事：命中就塞一句很短的提醒，把注意力拉回到"先办再回话"。
 *
 * 【误判的代价】
 * 多一句提示，模型可能多花一点力气去做事 —— 最坏情况是她对一句闲聊
 * 认真回应了一下，比"该做的事情没做"轻得多。所以宁可宽一点。
 */

/** 对方在指使她做具体的事。动词必须在列表里，「给我滚」这种不算。 */
const REQUEST_PATTERNS = [
  /帮我(?:找|搜|查|看|发|下|弄|做|写|换|问|买|订)/,
  /帮忙(?:找|搜|查|看|发|下|弄|做|写|换|问)/,
  /(?:你|那)(?:去|来)(?:找|搜|查|发|下|换|弄|做|写|买)/,
  /(?:快|赶紧|马上)(?:去)?(?:找|搜|查|发|下|换)/,
  /(?:找一张|找张|找几张|找几个)/,
  /(?:搜一下|搜个|搜张|搜一下|查一下|查查|查查资料)/,
  /(?:发个表情|发张表情|发一张表情|发表情包|发个图|发张图|来张表情|来个表情)/,
  /(?:换个头像|换头像|改个名|改名字)/,
  /(?:发条说说|发个说说|发说说)/,
  /(?:下载|下个|下一个)(?:一下)?(?:图|表情|视频|这个|那个)/,
  /给我(?:找|搜|发|查|下|弄|换)/
]

/** 明显是在开玩笑 / 骂人 / 反问，不算指令 */
const NOT_REQUEST = [
  /你要不要(?:试试|去死|滚)/,
  /^滚/,
  /给我滚/
]

/**
 * @param {string} text 对方发来的纯文本
 * @returns {string} 要注入的提示；'' 表示这不是指令
 */
export function requestHint(text) {
  const s = String(text || '').trim()
  if (!s || s.length > 300) return ''
  if (NOT_REQUEST.some((re) => re.test(s))) return ''
  if (!REQUEST_PATTERNS.some((re) => re.test(s))) return ''
  return (
    '【他这句是在**让你做事**，不是闲聊】先把它办了，再回话。\n' +
    '办完可以顺口吐槽一句（「行行行 这就去」），但事情得真办 —— ' +
    '别只回一句「好啊」「我看看」然后什么都没做，那不是真人，那是敷衍。\n' +
    '真做不到（工具报错、你没这个能力）就直说做不到，别假装做了。\n'
  )
}
