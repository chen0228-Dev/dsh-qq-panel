/** 按职业取模板；不认识的职业退回「自由自在」 */
export function templateFor(job) {
  return TEMPLATES[job] || TEMPLATES.free
}

/** 模板里有哪些职业可选（面板下拉用） */
export function jobOptions() {
  return Object.entries(JOBS).map(([key, v]) => ({ key, ...v }))
}

/**
 * 把旧配置（只有 age/grade/major/classSlots 的学生）映射成新结构。
 * 升级后老部署不改配置也不能变行为 —— 这是硬要求。
 */
export function legacyToRoutine(campus) {
  const c = campus || {}
  const job = c.job || 'student'
  return {
    version: 1,
    source: `template:${job}`,
    job,
    slots: (templateFor(job).slots || []).map((s) => ({ ...s })),
    events: (templateFor(job).events || []).map((e) => ({ ...e })),
    eventsPerDay: c.eventsPerDay ?? 1
  }
}
