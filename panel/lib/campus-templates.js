/**
 * 人格状态机的「日程模板库」。
 *
 * 为什么单独一个文件：campus.js 负责「怎么算状态」，这里负责「不同的人过什么样的日子」。
 * 以后想加职业、改文案，只动这个文件，不用碰状态机逻辑。
 *
 * 模板结构：
 *   slots  —— 一天里固定会发生的段落（几点到几点、在干嘛、忙到什么程度）
 *   events —— 活动池。每天按日期种子抽 1-2 个，制造「今天打球、明天游泳」的新鲜感。
 *             不抽的话天天一模一样，比没有状态还假。
 *
 * busy 档位是硬契约，全项目四个模块依赖它，不要改语义：
 *   0 闲（能随便聊）
 *   1 有点忙（能回，但简短）
 *   2 正忙（不该主动找人，回得慢）
 *   3 睡着（基本不理）
 */

/** 中文数字，用来拼「大二」「初三」这种年级 */
const CN = ['零', '一', '二', '三', '四', '五', '六', '七', '八', '九']

/** 按年龄推年级。学生这个身份下，年龄决定年级，不用人再填一遍 */
export function gradeForAge(age) {
  const a = Number(age) || 20
  if (a <= 6) return '幼儿园'
  if (a <= 12) return `小学${CN[Math.max(1, a - 6)] || ''}年级` // 7 岁一年级
  if (a <= 15) return `初${CN[a - 12] || ''}` // 13 初一
  if (a < 18) return `高${CN[a - 15] || ''}` // 16 高一
  if (a <= 21) return `大${CN[a - 17] || ''}` // 18 大一
  return '研究生'
}

